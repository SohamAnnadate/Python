# Sequence of characters after backslash "\" are called Escape Sequence characters.
# These characters represent one special character inside strings

'''
\n : new line
\t : tab
\' : single quote
\\ : backslash
'''
# Escape Sequence Characters in Python

# 1. \n (New Line)
print("Hello\nWorld")
# Output:
# Hello
# World


# 2. \t (Horizontal Tab)
print("Name\tAge")
# Output:
# Name    Age


# 3. \\ (Backslash)
print("C:\\Users\\Soham")
# Output:
# C:\Users\Soham


# 4. \' (Single Quote)
print('It\'s Python')
# Output:
# It's Python


# 5. \" (Double Quote)
print("He said, \"Hello!\"")
# Output:
# He said, "Hello!"


# 6. \b (Backspace)
print("Helloo\b")
# Output:
# Hello